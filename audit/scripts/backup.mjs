import Database from "better-sqlite3";
import { resolve } from "node:path";
import { mkdirSync } from "node:fs";
const source = resolve(process.env.AUDIT_DATA_DIR ?? "data", "audit.sqlite");
const target = process.argv[2];
if (!target) throw new Error("Pass a backup destination filename.");
mkdirSync(resolve(target, ".."), { recursive: true });
const db = new Database(source, { readonly: true, fileMustExist: true });
await db.backup(resolve(target));
db.close();
console.log("Consistent database backup completed.");
